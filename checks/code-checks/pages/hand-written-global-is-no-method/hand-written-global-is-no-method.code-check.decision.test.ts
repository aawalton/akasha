import { expect, test } from "bun:test"
import {
  globalsIn,
  isGenerated,
  methodsIn,
  reasonsIn,
  surfaceIn,
} from "./hand-written-global-is-no-method.code-check.decision.code.ts"

const OBJECTS = `interface AddOnManager {
  GetAddOnInfo: (index?: number) => string
  AreAddOnsEnabled(): boolean
  addOnCount: number
}
`

const GLOBALS = `declare function ReloadUI(this: void): void
declare const GetAddOnInfo: (index?: number) => string
declare const MAX_ADDONS: number
`

test("a member typed as a function is read as a method beside a method signature", () => {
  expect(methodsIn("objects.d.ts", OBJECTS)).toEqual(["GetAddOnInfo", "AreAddOnsEnabled"])
})

test("a member holding no function is no method", () => {
  expect(methodsIn("objects.d.ts", OBJECTS)).not.toContain("addOnCount")
})

test("a declared function and a declared const holding a function are both globals", () => {
  expect(globalsIn("functions.d.ts", GLOBALS)).toEqual([
    { name: "ReloadUI", line: 1, keyword: "function" },
    { name: "GetAddOnInfo", line: 2, keyword: "const" },
  ])
})

test("a hand-written global naming a method and no generated global is refused", () => {
  const held = surfaceIn([{ path: "objects.d.ts", text: OBJECTS }])
  const said = reasonsIn(globalsIn("extra.d.ts", GLOBALS), held)
  expect(said).toHaveLength(1)
  expect(said[0]).toContain("GetAddOnInfo")
})

test("a name the generated declarations carry as a global is let through", () => {
  const held = surfaceIn([
    { path: "objects.d.ts", text: OBJECTS },
    { path: "functions.d.ts", text: GLOBALS },
  ])
  expect(reasonsIn(globalsIn("extra.d.ts", GLOBALS), held)).toEqual([])
})

test("a page states it is generated by carrying the record", () => {
  expect(isGenerated({ generated: { writtenBy: "akasha temper-eso-generate-typings" } })).toBe(true)
  expect(isGenerated({ slug: "eso-extra" })).toBe(false)
  expect(isGenerated(null)).toBe(false)
})
