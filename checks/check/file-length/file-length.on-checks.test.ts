import { expect, test } from "bun:test"
import fileLength from "./file-length.ts"
import { CEILING_BYTES } from "./file-length.ts"

const ROOT = "/repo"

const OVER = "x".repeat(CEILING_BYTES + 1)

const UNDER = "x".repeat(CEILING_BYTES)

function verdict(path: string, body: string): readonly string[] {
  return fileLength.run({ root: ROOT, path: `${ROOT}/${path}`, body: Buffer.from(body) })
}

test("an authored file over the ceiling fails", () => {
  expect(verdict("page/thing.ts", OVER)).toHaveLength(1)
})

test("an authored file at the ceiling passes", () => {
  expect(verdict("page/thing.ts", UNDER)).toEqual([])
})

test("a lockfile over the ceiling passes", () => {
  expect(verdict("bun.lock", OVER)).toEqual([])
})

test("a lockfile in a nested package over the ceiling passes", () => {
  expect(verdict("native-shell/smilingjenny/bun.lock", OVER)).toEqual([])
})

test("an npm lockfile over the ceiling passes", () => {
  expect(verdict("native-shell/atlas/package-lock.json", OVER)).toEqual([])
})

test("a file merely named like a lockfile still fails", () => {
  expect(verdict("notes/bun.lock.txt", OVER)).toHaveLength(1)
  expect(verdict("notes/not-bun.lock", OVER)).toHaveLength(1)
  expect(verdict("notes/my-package-lock.json", OVER)).toHaveLength(1)
})

test("a file under a generated directory over the ceiling passes", () => {
  expect(verdict("page/generated/types.ts", OVER)).toEqual([])
})

test("a file carrying a generated header over the ceiling passes", () => {
  expect(verdict("page/thing.ts", `// @generated by something\n${OVER}`)).toEqual([])
})

test("a body that is not UTF-8 is judged on its length", () => {
  const bytes = Buffer.alloc(CEILING_BYTES + 1, 0xff)
  expect(fileLength.run({ root: ROOT, path: `${ROOT}/page/blob.bin`, body: bytes })).toHaveLength(1)
})
