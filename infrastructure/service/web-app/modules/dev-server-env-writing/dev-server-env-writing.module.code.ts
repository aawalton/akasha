import { readFileSync, writeFileSync } from "node:fs"
import { parseEnv } from "node:util"
import { valuesFor } from "akasha/infrastructure/service/secret/modules/saying/secret-saying.module.code.ts"
import { lookupApp } from "akasha/infrastructure/service/web-app/modules/dev-server-stating/dev-server-stating.module.code.ts"

function escapeEnvValue(value: string): string {
  const needsQuote = /[\s"'\\$`#=]/.test(value) || value === ""
  if (!needsQuote) return value
  const escaped = value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")
  return `"${escaped}"`
}

export function resolveEnvLocalPath(root: string, treePath: string, appName: string): string {
  const app = lookupApp(root, appName)
  return `${treePath}/${app.packagePath}/.env.local`
}

export function readEnvLocal(path: string): Record<string, string> {
  const parsed = parseEnv(readFileSync(path, "utf-8"))
  const out: Record<string, string> = {}
  for (const [key, value] of Object.entries(parsed)) {
    if (typeof value === "string") out[key] = value
  }
  return out
}

export function wroteEnvSaid(path: string, varCount: number): string {
  return `${path} was written with ${varCount} secret values in it, readable by its owner alone`
}

export function writeEnvLocalFromPages(params: {
  readonly root: string
  readonly treePath: string
  readonly appName: string
}): { readonly path: string; readonly varCount: number } {
  const { root, treePath, appName } = params
  const app = lookupApp(root, appName)
  const envPath = `${treePath}/${app.packagePath}/.env.local`

  const kv = new Map(Object.entries(valuesFor(treePath, app.secretResource)))

  const lines: string[] = []
  lines.push("# Generated by `akasha infrastructure dev-server bootstrap` — do not commit.")
  lines.push(`# app=${appName} secret=${app.secretResource}`)
  for (const [key, value] of kv.entries()) {
    lines.push(`${key}=${escapeEnvValue(value)}`)
  }
  writeFileSync(envPath, `${lines.join("\n")}\n`, { mode: 0o600 })

  return { path: envPath, varCount: kv.size }
}
