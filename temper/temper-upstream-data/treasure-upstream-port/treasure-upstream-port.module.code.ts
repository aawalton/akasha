import { readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"
import { addonsDir } from "@akasha/temper-eso-paths/eso-paths-resolve"
import { makeLuaVm } from "@akasha/temper-lua-runner/lua-vm"
import { PACKAGE_OF } from "../upstream-libraries/upstream-libraries.module.code.ts"

const SOURCE_PATH = join(addonsDir(), "LibTreasure", "data.lua")

const OUT_REL = "src/generated/treasure-pins-data.generated.ts"

// LibTreasure's tables are pure arrays where the shared serializer would write objects,
// so this one keeps its own array-aware serializer rather than reaching for that module.
const SERIALIZER = `
local function fmt_number(n)
  if n ~= n or n == math.huge or n == -math.huge then
    error("non-finite number in data: " .. tostring(n))
  end
  if n == math.floor(n) and math.abs(n) < 2^53 then
    return string.format("%d", n)
  end
  local s = string.format("%.14g", n)
  if tonumber(s) == n then return s end
  return string.format("%.17g", n)
end

local function fmt_string(s)
  local out = s:gsub("\\\\", "\\\\\\\\"):gsub('"', '\\\\"'):gsub("\\n", "\\\\n"):gsub("\\r", "\\\\r"):gsub("\\t", "\\\\t")
  return '"' .. out .. '"'
end

local function is_pure_array(t)
  local count = 0
  for k in pairs(t) do
    if type(k) ~= "number" or k ~= math.floor(k) or k < 1 then return false end
    count = count + 1
  end
  for i = 1, count do
    if t[i] == nil then return false end
  end
  return true
end

local function sorted_keys(t)
  local nums, strs = {}, {}
  for k in pairs(t) do
    if type(k) == "number" then
      nums[#nums + 1] = k
    elseif type(k) == "string" then
      strs[#strs + 1] = k
    else
      error("unsupported key type: " .. type(k))
    end
  end
  table.sort(nums)
  table.sort(strs)
  local out = {}
  for _, k in ipairs(nums) do out[#out + 1] = k end
  for _, k in ipairs(strs) do out[#out + 1] = k end
  return out
end

local TS_IDENT = "^[A-Za-z_][A-Za-z0-9_]*$"

function serialize_ts(v, indent)
  local t = type(v)
  if t == "number" then return fmt_number(v) end
  if t == "string" then return fmt_string(v) end
  if t == "boolean" then return tostring(v) end
  if t ~= "table" then error("unsupported value type: " .. t) end
  local pad = string.rep("  ", indent)
  local pad2 = string.rep("  ", indent + 1)
  if is_pure_array(v) then
    if #v == 0 then return "[]" end
    local parts = {}
    for i = 1, #v do
      parts[#parts + 1] = pad2 .. serialize_ts(v[i], indent + 1)
    end
    return "[\\n" .. table.concat(parts, ",\\n") .. ",\\n" .. pad .. "]"
  end
  local keys = sorted_keys(v)
  if #keys == 0 then return "{}" end
  local parts = {}
  for _, k in ipairs(keys) do
    local key
    if type(k) == "number" then
      key = "[" .. fmt_number(k) .. "]"
    elseif k:find(TS_IDENT) then
      key = k
    else
      key = fmt_string(k)
    end
    parts[#parts + 1] = pad2 .. key .. ": " .. serialize_ts(v[k], indent + 1)
  end
  return "{\\n" .. table.concat(parts, ",\\n") .. ",\\n" .. pad .. "}"
end
`

const HEADER = `// Generated by \`ops temper upstream-data port lib-treasure\` from upstream LibTreasure v24 \`data.lua\` — do not edit by hand.
// Re-run \`ops temper upstream-data port lib-treasure --code-root <code-checkout>\` to refresh against a new upstream version.
import type { AllData } from "../types"

export const ALL_DATA: AllData = `

export async function port(codeRoot: string): Promise<void> {
  const outPath = join(codeRoot, PACKAGE_OF["lib-treasure"], OUT_REL)
  const source = await readFile(SOURCE_PATH, "utf-8")
  const vm = await makeLuaVm({ stubs: SERIALIZER })
  try {
    const exported = `${source}\nLibTreasure.__ALL_DATA = ALL_DATA\n`
    const script = `
      LibTreasure = { data = {} }
      local chunk = assert(loadstring(${JSON.stringify(exported)}))
      local ok, err = pcall(chunk)
      if not ok then error("running data.lua failed: " .. tostring(err)) end
      local allData = LibTreasure.__ALL_DATA
      if type(allData) ~= "table" then error("ALL_DATA not captured") end
      local n = 0
      for _ in pairs(allData) do n = n + 1 end
      if n == 0 then error("ALL_DATA is empty") end
      return serialize_ts(allData, 0)
    `
    const serialized = await vm.run(script)
    if (typeof serialized !== "string") {
      throw new Error(`serializer returned ${typeof serialized}, expected string`)
    }
    await writeFile(outPath, `${HEADER}${serialized}\n`)
    console.log(`ported ${SOURCE_PATH} -> ${outPath}`)
  } finally {
    await vm.close()
  }
}
