import { mkdir, readdir, rm, writeFile } from "node:fs/promises"
import { join } from "node:path"
import { addonsDir } from "@akasha/temper-eso-paths/eso-paths-resolve"
import { makeLuaVm } from "@akasha/temper-lua-runner/lua-vm"
import { PACKAGE_OF } from "../upstream-libraries/upstream-libraries.module.code.ts"

const UPSTREAM_PATH = join(addonsDir(), "PortToFriendsHouse", "PortToFriendsHouseLibraryData.lua")

const DATA_REL = "src/ptf/data/generated"

const FILTER_IDS = {
  FILTER_ID_NONE: 1,
  FILTER_ID_HIGHLIGHT: 2,
  FILTER_ID_LABYRINTH: 3,
  FILTER_ID_JUMPNRUN: 4,
  FILTER_ID_CRAFTING: 5,
  FILTER_ID_GUILD: 6,
  FILTER_ID_ROLEPLAY: 7,
  FILTER_ID_RAID: 8,
  FILTER_ID_HIDE_SEEK: 9,
  FILTER_ID_ERP: 10,
} as const

interface LibraryEntry {
  readonly name: string
  readonly houseId: number
  readonly description: string
  readonly category: readonly number[]
}

const FILTER_CONST_LUA = Object.entries(FILTER_IDS)
  .map(([k, v]) => `    ${k} = ${v},`)
  .join("\n")

const PRELUDE = `
PortToFriend = {
  libData = {},
  constants = {
${FILTER_CONST_LUA}
  },
}
GetWorldName = function() return "EU Megaserver" end
return "ok"
`

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null
}

function parseEntries(raw: unknown, label: string): LibraryEntry[] {
  if (!Array.isArray(raw)) {
    throw new Error(`${label} did not marshal as an array (got ${typeof raw})`)
  }
  return raw.map((item, i) => {
    if (!isRecord(item)) {
      throw new Error(`${label}[${i}] is not a table`)
    }
    const { name, houseId, description, category } = item
    if (typeof name !== "string") {
      throw new Error(`${label}[${i}].name is not a string`)
    }
    if (typeof houseId !== "number") {
      throw new Error(`${label}[${i}].houseId is not a number`)
    }
    if (typeof description !== "string") {
      throw new Error(`${label}[${i}].description is not a string`)
    }
    if (!Array.isArray(category)) {
      throw new Error(`${label}[${i}].category is not an array`)
    }
    const cats = category.map((c, j) => {
      if (typeof c !== "number") {
        throw new Error(`${label}[${i}].category[${j}] is not a number`)
      }
      return c
    })
    return { name, houseId, description, category: cats }
  })
}

function serializeEntry(entry: LibraryEntry): string {
  const name = JSON.stringify(entry.name)
  const description = JSON.stringify(entry.description)
  const category = `[${entry.category.join(", ")}]`
  return [
    "  {",
    `    name: ${name},`,
    `    houseId: ${entry.houseId},`,
    `    description: ${description},`,
    `    category: ${category},`,
    "  },",
  ].join("\n")
}

const HEADER =
  "// Generated by `ops temper upstream-data port housing` from the upstream\n" +
  "// PortToFriendsHouseLibraryData.lua via deterministic Lua-VM extraction\n" +
  "// (data-extraction rule). Do not edit.\n"

const ENTRIES_PER_PART = 75

interface EmittedFile {
  readonly relPath: string
  readonly content: string
}

function emitPart(varName: string, entries: LibraryEntry[]): string {
  const body = entries.map(serializeEntry).join("\n")
  return (
    `${HEADER}import type { LibraryEntry } from "../../types"\n\n` +
    `export const ${varName}: LibraryEntry[] = [\n${body}\n]\n`
  )
}

function emitArray(
  varName: string,
  base: string,
  entries: LibraryEntry[]
): { files: EmittedFile[]; barrelImports: string; barrelStatement: string } {
  if (entries.length <= ENTRIES_PER_PART) {
    return {
      files: [{ relPath: `${base}.generated.ts`, content: emitPart(varName, entries) }],
      barrelImports: "",
      barrelStatement: `export { ${varName} } from "./${base}.generated"\n`,
    }
  }
  const files: EmittedFile[] = []
  const partVars: string[] = []
  for (let part = 0; part * ENTRIES_PER_PART < entries.length; part++) {
    const slice = entries.slice(part * ENTRIES_PER_PART, (part + 1) * ENTRIES_PER_PART)
    const partVar = `${varName}Part${part + 1}`
    partVars.push(partVar)
    files.push({
      relPath: `${base}-${part + 1}.generated.ts`,
      content: emitPart(partVar, slice),
    })
  }
  const barrelImports = partVars
    .map((v, i) => `import { ${v} } from "./${base}-${i + 1}.generated"\n`)
    .join("")
  const barrelStatement = `export const ${varName}: LibraryEntry[] = [${partVars.join(", ")}].flat()\n`
  return { files, barrelImports, barrelStatement }
}

export async function port(codeRoot: string): Promise<void> {
  const dataDir = join(codeRoot, PACKAGE_OF.housing, DATA_REL)
  const vm = await makeLuaVm({ stubs: PRELUDE })
  try {
    await mkdir(dataDir, { recursive: true })

    const setup = await vm.run(`
      local ok, err = pcall(dofile, ${JSON.stringify(UPSTREAM_PATH)})
      if not ok then error("dofile failed: " .. tostring(err)) end
      PortToFriend.libData.CreateEuDataList()
      PortToFriend.libData.CreateNaDataList()
      return "ok"
    `)
    if (setup !== "ok") {
      throw new Error(`upstream execution returned ${String(setup)}`)
    }

    const euRaw = await vm.run("return PortToFriend.libData.euData")
    const naRaw = await vm.run("return PortToFriend.libData.naData")
    const euData = parseEntries(euRaw, "euData")
    const naData = parseEntries(naRaw, "naData")

    for (const f of await readdir(dataDir)) {
      if (f.endsWith(".generated.ts")) await rm(join(dataDir, f))
    }

    const eu = emitArray("euLibraryData", "library-data-eu", euData)
    const na = emitArray("naLibraryData", "library-data-na", naData)

    const written: string[] = []
    for (const f of [...eu.files, ...na.files]) {
      await writeFile(join(dataDir, f.relPath), f.content)
      written.push(f.relPath)
    }

    const imports = `${eu.barrelImports}${na.barrelImports}`
    const typeImport = imports.length > 0 ? `import type { LibraryEntry } from "../../types"\n` : ""
    const barrelOut =
      `${HEADER}${typeImport}${imports}` +
      `${imports.length > 0 ? "\n" : ""}` +
      `${eu.barrelStatement}${na.barrelStatement}`
    await writeFile(join(dataDir, "library-data.generated.ts"), barrelOut)
    written.push("library-data.generated.ts (barrel)")

    console.log(`ported euData (${euData.length}) + naData (${naData.length})`)
    for (const f of written) console.log(`-> ${DATA_REL}/${f}`)
  } finally {
    await vm.close()
  }
}
