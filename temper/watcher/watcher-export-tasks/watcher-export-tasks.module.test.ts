const SUPABASE: SignedInReader = {
  auth: {
    getUser: async () => ({ data: { user: { id: "user-1" } }, error: null }),
  },
}

const SIGNED_OUT: SignedInReader = {
  auth: {
    getUser: async () => ({ data: { user: null }, error: { message: "session expired" } }),
  },
}

interface Seam {
  readonly options: ExportTasksOptions
  readonly written: { path: string; content: string }[]
  readonly patched: string[]
  readonly said: string[]
}

function recording(
  taskRows: readonly Page[],
  overrideRows: readonly Page[],
  extra: ExportTasksOptions = {}
): Seam {
  const written: { path: string; content: string }[] = []
  const patched: string[] = []
  const said: string[] = []

  const collect: PageCollect = async (args) => {
    if (args.pageTypeSlug === TASK_PAGE_TYPE_SLUG) return [...taskRows]
    if (args.pageTypeSlug === COMPLETION_OVERRIDE_PAGE_TYPE_SLUG) return [...overrideRows]
    return []
  }

  const getRows: PageGet = async (args) => {
    const rows = args.pageTypeSlug === CHARACTER_PAGE_TYPE_SLUG ? [...CHARACTER_ROWS] : []
    return { rows, nextCursor: null, count: null }
  }

  const patchRow: PagePatchById = async (args) => {
    patched.push(args.id)
    return null
  }

  return {
    options: {
      userId: "user-1",
      collect,
      getRows,
      patchRow,
      compilePriority: async () => ["1001", "1002"],
      writeSideFile: (path, content) => {
        written.push({ path, content })
        return WRITTEN_HASH
      },
      report: (message) => {
        said.push(message)
      },
      ...extra,
    },
    written,
    patched,
    said,
  }
}

test("the saved-variables content matches what the legacy export made of the same tasks", async () => {
  const seam = recording(TASK_ROWS, OVERRIDE_ROWS)
  const result = await runExportTasks(CONTENT, SUPABASE, seam.options)
  expect(result.content).toBe(LEGACY_CONTENT)
  expect(result.modified).toBe(true)
})

test("the config file matches what the legacy export made of the same tasks", async () => {
  const seam = recording(TASK_ROWS, OVERRIDE_ROWS, {
    charactersConfigPath: "/nowhere/characters.lua",
  })
  const result = await runExportTasks(CONTENT, SUPABASE, seam.options)
  expect(seam.written).toEqual([{ path: "/nowhere/characters.lua", content: LEGACY_SIDE_FILE }])
  expect(result.charactersConfigSideFileHash).toBe(WRITTEN_HASH)
})

test("no task at all still writes the config file the legacy export made", async () => {
  const seam = recording([], [], { charactersConfigPath: "/nowhere/characters.lua" })
  const result = await runExportTasks(CONTENT, SUPABASE, seam.options)
  expect(seam.written).toEqual([
    { path: "/nowhere/characters.lua", content: LEGACY_EMPTY_SIDE_FILE },
  ])
  expect(result.content).toBe(CONTENT)
  expect(result.modified).toBe(false)
})

test("no task and no config path leaves the content alone and answers no hash", async () => {
  const seam = recording([], [])
  const result = await runExportTasks(CONTENT, SUPABASE, seam.options)
  expect(result).toEqual({ content: CONTENT, modified: false, charactersConfigSideFileHash: null })
  expect(seam.written).toEqual([])
  expect(seam.said).toEqual(["No tasks to export."])
})

test("a dry run writes no config file even where a path is given", async () => {
  const seam = recording(TASK_ROWS, OVERRIDE_ROWS, {
    charactersConfigPath: "/nowhere/characters.lua",
    dryRun: true,
  })
  const result = await runExportTasks(CONTENT, SUPABASE, seam.options)
  expect(seam.written).toEqual([])
  expect(result.charactersConfigSideFileHash).toBe(null)
  expect(result.content).toBe(LEGACY_CONTENT)
})

test("only a task awaiting sync is marked back, and every task is named", async () => {
  const seam = recording(TASK_ROWS, OVERRIDE_ROWS)
  await runExportTasks(CONTENT, SUPABASE, seam.options)
  expect(seam.patched).toEqual(["row-id-1"])
  expect(seam.said).toEqual([
    "Exporting 2 task(s).",
    "Cleared pendingSync on 1 task(s).",
    "Task row-id-1: Daily writs",
    "Task row-id-2: ",
  ])
})

test("a task row carrying no page id is left out", async () => {
  const seam = recording([asPage({ title: "no id at all" })], [])
  const result = await runExportTasks(CONTENT, SUPABASE, seam.options)
  expect(result.modified).toBe(false)
  expect(seam.said).toEqual(["No tasks to export."])
})

test("a task is keyed by its page id", () => {
  expect(taskKey(asPage({ id: "row-id-1" }))).toBe("row-id-1")
  expect(taskKey(asPage({ id: "row-id-2" }))).toBe("row-id-2")
})

test("a task row holding nothing falls back to an empty title and the account scope", () => {
  expect(taskDataFrom(asPage({ id: "row" }), null)).toEqual({
    title: "",
    description: null,
    rrule: null,
    dueDate: null,
    dueTime: null,
    scope: "account",
    esoCharacterId: null,
    sortOrder: 0,
    priority: null,
    completionCardId: null,
    completionItemPath: null,
  })
})

test("an item path holding anything but text and numbers reads as nothing", () => {
  expect(itemPathAt({ path: ["alchemy", 2] }, "path")).toEqual(["alchemy", 2])
  expect(itemPathAt({ path: [] }, "path")).toEqual([])
  expect(itemPathAt({ path: ["alchemy", { deep: true }] }, "path")).toBe(null)
  expect(itemPathAt({ path: "alchemy" }, "path")).toBe(null)
  expect(itemPathAt({}, "path")).toBe(null)
})

test("an override with an unknown card, or an unknown character, reaches no config file", async () => {
  const seam = recording(TASK_ROWS, OVERRIDE_ROWS, {
    charactersConfigPath: "/nowhere/characters.lua",
  })
  await runExportTasks(CONTENT, SUPABASE, seam.options)
  const written = seam.written[0]?.content ?? ""
  expect(written).toContain("daily-writs")
  expect(written).not.toContain("hireling-mails")
  expect(written).not.toContain("no-such-card")
})

test("a run with no signed-in user is refused, naming what the session said", async () => {
  const seam = recording(TASK_ROWS, OVERRIDE_ROWS, { userId: undefined })
  await expect(runExportTasks(CONTENT, SIGNED_OUT, seam.options)).rejects.toThrow(
    "no signed-in user to export these tasks (session expired)"
  )
})
