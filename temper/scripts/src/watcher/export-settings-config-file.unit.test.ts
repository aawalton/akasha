import { describe, expect, test } from "bun:test"
import {
  type InventoryConfigFileInputs,
  serializeInventoryConfigFile,
} from "./export-settings-config-file"

const INVENTORY_CONFIG_REQUIRED_KEYS = [
  "version",
  "logging",
  "safety",
  "backpack",
  "currencyRates",
  "crownReplacementCosts",
] as const

const INVENTORY_CONFIG_OPTIONAL_KEYS = [
  "sell",
  "sellTimestamps",
  "sellCompiled",
  "automation",
] as const

const minimalInputs = {
  logging: { actionReports: "verbose", perfTracing: "none" },
  safety: {
    confirmActions: ["deconstruct", "sell", "research", "destroy"],
    openCooldownProtection: true,
  },
  backpack: { bufferSlots: 5, autoStack: true },
  currencyRates: {},
  crownReplacementCosts: {},
} as const satisfies InventoryConfigFileInputs

const fullInputs: InventoryConfigFileInputs = {
  sell: { trash: "sell", usedBait: "sell" },
  sellTimestamps: { "abc:def": 1700000000 },
  sellCompiled: { rules: [], itemRules: [] },
  logging: { actionReports: "minimal", perfTracing: "minimal" },
  safety: {
    confirmActions: ["destroy"],
    openCooldownProtection: false,
  },
  automation: {
    characters: { "char-1": { equipment: true } },
    companions: { "comp-1": { equipment: true } },
  },
  backpack: { bufferSlots: 0, autoStack: false },
  currencyRates: { gold: 1, telvarStones: 0.12, alliancePoints: 0.05, writVouchers: 80 },
  crownReplacementCosts: { 64711: 1200, 64710: 350, 112427: 900, 112428: 950 },
}

describe("serializeInventoryConfigFile", () => {
  test("emits the documented header and top-level assignment", () => {
    const out = serializeInventoryConfigFile(minimalInputs)
    expect(out.startsWith("-- Auto-generated by the Temper watcher; do not edit by hand.\n")).toBe(
      true
    )
    expect(out).toContain("TemperInventoryConfig =\n{\n")
    expect(out.endsWith("}\n")).toBe(true)
  })

  test("emits version stamp first", () => {
    const out = serializeInventoryConfigFile(minimalInputs)
    const lines = out.split("\n")
    const openIdx = lines.indexOf("{")
    expect(openIdx).toBeGreaterThanOrEqual(0)
    expect(lines[openIdx + 1]).toBe('    ["version"] = 1,')
  })

  test("emits every required key on minimal inputs", () => {
    const out = serializeInventoryConfigFile(minimalInputs)
    for (const key of INVENTORY_CONFIG_REQUIRED_KEYS) {
      expect(out).toContain(`["${key}"]`)
    }
  })

  test("omits optional keys when inputs leave them undefined", () => {
    const out = serializeInventoryConfigFile(minimalInputs)
    for (const key of INVENTORY_CONFIG_OPTIONAL_KEYS) {
      expect(out).not.toContain(`["${key}"]`)
    }
  })

  test("emits every required and optional key on full inputs", () => {
    const out = serializeInventoryConfigFile(fullInputs)
    for (const key of INVENTORY_CONFIG_REQUIRED_KEYS) {
      expect(out).toContain(`["${key}"]`)
    }
    for (const key of INVENTORY_CONFIG_OPTIONAL_KEYS) {
      expect(out).toContain(`["${key}"]`)
    }
  })

  test("emits no unexpected top-level keys", () => {
    const out = serializeInventoryConfigFile(fullInputs)
    const topLevelKeys = extractTopLevelKeys(out)
    const expected = new Set<string>([
      ...INVENTORY_CONFIG_REQUIRED_KEYS,
      ...INVENTORY_CONFIG_OPTIONAL_KEYS,
    ])
    expect(new Set(topLevelKeys)).toEqual(expected)
  })

  test("produces byte-identical output on repeated calls (minimal inputs)", () => {
    const a = serializeInventoryConfigFile(minimalInputs)
    const b = serializeInventoryConfigFile(minimalInputs)
    expect(a).toBe(b)
  })

  test("produces byte-identical output on repeated calls (full inputs)", () => {
    const a = serializeInventoryConfigFile(fullInputs)
    const b = serializeInventoryConfigFile(fullInputs)
    expect(a).toBe(b)
  })

  test("preserves the documented key order", () => {
    const out = serializeInventoryConfigFile(fullInputs)
    const indices = [
      "version",
      "sell",
      "sellTimestamps",
      "sellCompiled",
      "logging",
      "safety",
      "automation",
      "backpack",
      "currencyRates",
      "crownReplacementCosts",
    ].map((k) => out.indexOf(`["${k}"]`))
    for (let i = 1; i < indices.length; i++) {
      const prev = indices[i - 1] ?? -1
      const cur = indices[i] ?? -1
      expect(cur).toBeGreaterThan(prev)
    }
  })

  test("emits both pricing tables as empty Lua tables on the fallback case", () => {
    const out = serializeInventoryConfigFile(minimalInputs)
    expect(out).toContain('["currencyRates"] =\n    {},')
    expect(out).toContain('["crownReplacementCosts"] =\n    {},')
  })

  test("serializes populated currencyRates as a string-keyed table", () => {
    const out = serializeInventoryConfigFile(fullInputs)
    expect(out).toContain('["gold"] = 1')
    expect(out).toContain('["telvarStones"] = 0.12')
    expect(out).toContain('["alliancePoints"] = 0.05')
    expect(out).toContain('["writVouchers"] = 80')
  })

  test("serializes populated crownReplacementCosts with numeric Lua keys", () => {
    const out = serializeInventoryConfigFile(fullInputs)
    expect(out).toContain("[64711] = 1200")
    expect(out).toContain("[64710] = 350")
    expect(out).toContain("[112427] = 900")
    expect(out).toContain("[112428] = 950")
  })
})

function extractTopLevelKeys(out: string): readonly string[] {
  const keys: string[] = []
  const lines = out.split("\n")
  let depth = 0
  const KEY_PREFIX = '    ["'
  const KEY_SUFFIX = '"]'
  for (const line of lines) {
    const opens = countChar(line, "{")
    const closes = countChar(line, "}")
    if (depth === 1 && line.startsWith(KEY_PREFIX)) {
      const end = line.indexOf(KEY_SUFFIX, KEY_PREFIX.length)
      if (end > KEY_PREFIX.length) {
        keys.push(line.slice(KEY_PREFIX.length, end))
      }
    }
    depth += opens - closes
  }
  return keys
}

function countChar(s: string, ch: string): number {
  let n = 0
  for (const c of s) if (c === ch) n += 1
  return n
}
