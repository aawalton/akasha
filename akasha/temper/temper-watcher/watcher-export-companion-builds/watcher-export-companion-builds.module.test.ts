import { expect, test } from "bun:test"
import type { Page } from "@akasha/pages-core/page-types"
import { asPage } from "@akasha/pages-core/page-types"
import type {
  SignedInAnswer,
  SignedInReader,
} from "../watcher-signed-in-user/watcher-signed-in-user.module.code.ts"
import type { CompanionBuildsSurroundings } from "./watcher-export-companion-builds.module.code.ts"
import {
  readTargetBuilds,
  runExportCompanionBuilds,
  sameTargetBuilds,
  targetsAsConfigInputs,
  updatedAtSeconds,
  withTargetBuilds,
} from "./watcher-export-companion-builds.module.code.ts"

const NOW = 1650000000000

const WITH_BLOCK =
  'TemperCompanions =\n{\n    ["Default"] =\n    {\n        ["@alan"] =\n        {\n            ["companions"] =\n            {\n                [1] = "x",\n            },\n            ["companionTargetBuilds"] =\n            {\n                [3] = "aaa",\n                [7] = "bbb",\n            },\n            ["companionTargetTimestamps"] =\n            {\n                [3] = 1600000000,\n                [7] = 1600000001,\n            },\n        },\n    },\n}\n'

const WITHOUT_BLOCK =
  'TemperCompanions =\n{\n    ["Default"] =\n    {\n        ["@alan"] =\n        {\n            ["selectedCompanionId"] = "c1",\n            ["companions"] =\n            {\n                [1] = "x",\n            },\n        },\n    },\n}\n'

const REPLACED =
  'TemperCompanions =\n{\n    ["Default"] =\n    {\n        ["@alan"] =\n        {\n            ["companions"] =\n            {\n                [1] = "x",\n            },\n            ["companionTargetBuilds"] =\n            {\n                [3] = "new3",\n                [7] = "new7",\n            },\n            ["companionTargetTimestamps"] =\n            {\n                [3] = 1700000000,\n                [7] = 1700000001,\n            },\n        },\n    },\n}\n'

const INSERTED =
  'TemperCompanions =\n{\n    ["Default"] =\n    {\n        ["@alan"] =\n        {\n            ["selectedCompanionId"] = "c1",\n            ["companionTargetBuilds"] =\n            {\n                [2] = "b",\n                [10] = "j",\n            },\n            ["companionTargetTimestamps"] =\n            {\n                [2] = 1700000002,\n                [10] = 1700000010,\n            },\n            ["companions"] =\n            {\n                [1] = "x",\n            },\n        },\n    },\n}\n'

const EXPORTED =
  'TemperCompanions =\n{\n    ["Default"] =\n    {\n        ["@alan"] =\n        {\n            ["selectedCompanionId"] = "c1",\n            ["companionTargetBuilds"] =\n            {\n                [1] = "hash-bastian",\n                [2] = "hash-mirri",\n            },\n            ["companionTargetTimestamps"] =\n            {\n                [1] = 1700000000,\n                [2] = 1600000000,\n            },\n            ["companions"] =\n            {\n                [1] = "x",\n            },\n        },\n    },\n}\n'

const SIDE_FILE =
  '-- Auto-generated by the Temper watcher; do not edit by hand.\nTemperCompanionsConfig =\n{\n    ["version"] = 1,\n    ["companionTargetBuilds"] =\n    {\n        [1] = "hash-bastian",\n        [2] = "hash-mirri",\n    },\n    ["companionTargetTimestamps"] =\n    {\n        [1] = 1700000000,\n        [2] = 1600000000,\n    },\n}\n'

const EMPTY_SIDE_FILE =
  '-- Auto-generated by the Temper watcher; do not edit by hand.\nTemperCompanionsConfig =\n{\n    ["version"] = 1,\n    ["companionTargetBuilds"] = {},\n    ["companionTargetTimestamps"] = {},\n}\n'

const PROGRESS: readonly Page[] = [
  asPage({ companionId: "bastian", targetBuildId: "b-bastian" }),
  asPage({ companionId: "mirri", targetBuildId: "b-mirri" }),
]

const BUILDS: Readonly<Record<string, Page>> = {
  "b-bastian": asPage({ buildHash: "hash-bastian", updatedAt: "2023-11-14T22:13:20.000Z" }),
  "b-mirri": asPage({ buildHash: "hash-mirri", updatedAt: 1600000000000 }),
}

interface Recording {
  readonly surroundings: CompanionBuildsSurroundings
  readonly notes: string[]
  readonly errors: string[]
  readonly written: { path: string; desired: string }[]
}

function recording(
  progress: readonly Page[] = PROGRESS,
  builds: Readonly<Record<string, Page>> = BUILDS
): Recording {
  const notes: string[] = []
  const errors: string[] = []
  const written: { path: string; desired: string }[] = []
  return {
    notes,
    errors,
    written,
    surroundings: {
      progressPages: async () => progress,
      buildPage: async (buildId) => builds[buildId] ?? null,
      writeSideFile: (path, desired) => {
        written.push({ path, desired })
        return "side-file-hash"
      },
      now: () => NOW,
      note: (message) => {
        notes.push(message)
        return undefined
      },
      noteError: (message) => {
        errors.push(message)
        return undefined
      },
    },
  }
}

function supabaseAnswering(answer: SignedInAnswer): SignedInReader {
  return { auth: { getUser: async () => answer } }
}

const SIGNED_OUT = supabaseAnswering({ data: { user: null }, error: null })

test("the target builds a saved-variables file already holds are read back out of it", () => {
  expect(readTargetBuilds(WITH_BLOCK)).toEqual({ 3: "aaa", 7: "bbb" })
})

test("content with no target builds block reads as no target build", () => {
  expect(readTargetBuilds(WITHOUT_BLOCK)).toEqual({})
})

test("two maps of target builds match only where every key and value agrees", () => {
  expect(sameTargetBuilds({ 3: "aaa", 7: "bbb" }, { 3: "aaa", 7: "bbb" })).toBe(true)
  expect(sameTargetBuilds({ 3: "aaa" }, { 3: "zzz" })).toBe(false)
  expect(sameTargetBuilds({ 3: "aaa" }, { 3: "aaa", 7: "bbb" })).toBe(false)
})

test("a block already in the content is replaced in place", () => {
  expect(
    withTargetBuilds(WITH_BLOCK, {
      companionTargetBuilds: { 3: "new3", 7: "new7" },
      companionTargetTimestamps: { 3: 1700000000, 7: 1700000001 },
    })
  ).toBe(REPLACED)
})

test("a block absent is inserted before the first sibling found", () => {
  expect(
    withTargetBuilds(WITHOUT_BLOCK, {
      companionTargetBuilds: { 10: "j", 2: "b" },
      companionTargetTimestamps: { 10: 1700000010, 2: 1700000002 },
    })
  ).toBe(INSERTED)
})

test("a time given as text comes out in whole seconds", () => {
  expect(updatedAtSeconds("2023-11-14T22:13:20.000Z", NOW)).toBe(1700000000)
})

test("a time given as milliseconds comes out in whole seconds", () => {
  expect(updatedAtSeconds(1600000000500, NOW)).toBe(1600000000)
})

test("a time that will not parse is taken as the time of the export", () => {
  expect(updatedAtSeconds("whenever", NOW)).toBe(1650000000)
  expect(updatedAtSeconds(undefined, NOW)).toBe(1650000000)
})

test("targets become the two blocks the config file wants", () => {
  expect(
    targetsAsConfigInputs([
      { defId: 2, buildHash: "hash-mirri", seconds: 1600000000 },
      { defId: 1, buildHash: "hash-bastian", seconds: 1700000000 },
    ])
  ).toEqual({
    companionTargetBuilds: { 1: "hash-bastian", 2: "hash-mirri" },
    companionTargetTimestamps: { 1: 1700000000, 2: 1600000000 },
  })
})

test("every target build reaches the saved-variables file and the side file", async () => {
  const { surroundings, written, notes } = recording()
  const result = await runExportCompanionBuilds(
    WITHOUT_BLOCK,
    SIGNED_OUT,
    { userId: "alan", companionsConfigPath: "/nowhere/companions.lua" },
    surroundings
  )
  expect(result.content).toBe(EXPORTED)
  expect(result.modified).toBe(true)
  expect(result.companionsConfigSideFileHash).toBe("side-file-hash")
  expect(written).toEqual([{ path: "/nowhere/companions.lua", desired: SIDE_FILE }])
  expect(notes).toEqual([
    "exporting 2 companion target build(s)",
    "companion 1 takes build hash-bastian",
    "companion 2 takes build hash-mirri",
  ])
})

test("content already holding every target build is handed back unchanged", async () => {
  const { surroundings, notes } = recording()
  const result = await runExportCompanionBuilds(
    EXPORTED,
    SIGNED_OUT,
    { userId: "alan" },
    surroundings
  )
  expect(result.content).toBe(EXPORTED)
  expect(result.modified).toBe(false)
  expect(notes).toEqual(["the saved-variables file already holds every companion target build"])
})

test("no target build set still writes an empty side file", async () => {
  const { surroundings, written, notes } = recording([])
  const result = await runExportCompanionBuilds(
    WITHOUT_BLOCK,
    SIGNED_OUT,
    { userId: "alan", companionsConfigPath: "/nowhere/companions.lua" },
    surroundings
  )
  expect(result.modified).toBe(false)
  expect(written).toEqual([{ path: "/nowhere/companions.lua", desired: EMPTY_SIDE_FILE }])
  expect(notes).toEqual(["no companion target build is set, so none is exported"])
})

test("no side-file path given answers no hash and writes nothing beside the addon", async () => {
  const { surroundings, written } = recording()
  const result = await runExportCompanionBuilds(
    WITHOUT_BLOCK,
    SIGNED_OUT,
    { userId: "alan" },
    surroundings
  )
  expect(result.companionsConfigSideFileHash).toBe(null)
  expect(written).toEqual([])
})

test("a companion no id is known for is left out and named", async () => {
  const { surroundings, errors } = recording([
    asPage({ companionId: "nobody", targetBuildId: "b-bastian" }),
    ...PROGRESS,
  ])
  const result = await runExportCompanionBuilds(
    WITHOUT_BLOCK,
    SIGNED_OUT,
    { userId: "alan" },
    surroundings
  )
  expect(result.content).toBe(EXPORTED)
  expect(errors).toEqual([
    "no companion is known by the id nobody, so its target build is left out",
  ])
})

test("a build page absent leaves that companion out", async () => {
  const { surroundings } = recording(PROGRESS, {
    "b-bastian": asPage({ buildHash: "hash-bastian", updatedAt: "2023-11-14T22:13:20.000Z" }),
  })
  const result = await runExportCompanionBuilds(
    WITHOUT_BLOCK,
    SIGNED_OUT,
    { userId: "alan" },
    surroundings
  )
  expect(readTargetBuilds(result.content)).toEqual({ 1: "hash-bastian" })
})

test("a build carrying no hash leaves that companion out", async () => {
  const { surroundings } = recording(PROGRESS, {
    "b-bastian": asPage({ buildHash: "hash-bastian", updatedAt: "2023-11-14T22:13:20.000Z" }),
    "b-mirri": asPage({ updatedAt: 1600000000000 }),
  })
  const result = await runExportCompanionBuilds(
    WITHOUT_BLOCK,
    SIGNED_OUT,
    { userId: "alan" },
    surroundings
  )
  expect(readTargetBuilds(result.content)).toEqual({ 1: "hash-bastian" })
})

test("a user id the caller names is taken over the signed-in one", async () => {
  const asked: string[] = []
  const { surroundings } = recording()
  const result = await runExportCompanionBuilds(
    WITHOUT_BLOCK,
    SIGNED_OUT,
    { userId: "alan" },
    {
      ...surroundings,
      progressPages: async (userId) => {
        asked.push(userId)
        return PROGRESS
      },
    }
  )
  expect(asked).toEqual(["alan"])
  expect(result.modified).toBe(true)
})

test("a refused sign-in carries the reason given", async () => {
  const angry = supabaseAnswering({ data: { user: null }, error: { message: "token expired" } })
  const { surroundings } = recording()
  await expect(runExportCompanionBuilds(WITHOUT_BLOCK, angry, {}, surroundings)).rejects.toThrow(
    "no signed-in user to export these companion builds (token expired)"
  )
})

test("the signed-in user is asked for where the caller names none", async () => {
  const signedIn = supabaseAnswering({ data: { user: { id: "from-session" } }, error: null })
  const asked: string[] = []
  const { surroundings } = recording()
  await runExportCompanionBuilds(
    WITHOUT_BLOCK,
    signedIn,
    {},
    {
      ...surroundings,
      progressPages: async (userId) => {
        asked.push(userId)
        return PROGRESS
      },
    }
  )
  expect(asked).toEqual(["from-session"])
})
