import { expect, test } from "bun:test"
import {
  numericKeyedBlock,
  serializeCharactersConfigFile,
  serializeCompanionsConfigFile,
  serializeInventoryConfigFile,
} from "./watcher-config-file.module.code.ts"

test("the inventory config file matches what the legacy serializer wrote", () => {
  expect(
    serializeInventoryConfigFile({
      "sell": {
        "keep": 1,
      },
      "sellTimestamps": {
        "keep": 1700000000,
      },
      "sellCompiled": [
        {
          "id": "a",
        },
      ],
      "logging": {
        "level": "info",
      },
      "safety": {
        "destructive": false,
      },
      "backpack": {
        "reserved": 10,
      },
      "automation": {
        "deconstruct": true,
      },
      "currencyRates": {
        "gold": 1,
        "ap": 0.5,
      },
      "crownReplacementCosts": {
        "1": 2,
        "3": 4,
      },
    })
  ).toBe(
    '-- Auto-generated by the Temper watcher; do not edit by hand.\nTemperInventoryConfig =\n{\n    ["version"] = 1,\n    ["sell"] =\n    {\n        ["keep"] = 1,\n    },\n    ["sellTimestamps"] =\n    {\n        ["keep"] = 1700000000,\n    },\n    ["sellCompiled"] =\n    {\n        {\n            ["id"] = "a",\n        },\n    },\n    ["logging"] =\n    {\n        ["level"] = "info",\n    },\n    ["safety"] =\n    {\n        ["destructive"] = false,\n    },\n    ["automation"] =\n    {\n        ["deconstruct"] = true,\n    },\n    ["backpack"] =\n    {\n        ["reserved"] = 10,\n    },\n    ["currencyRates"] =\n    {\n        ["gold"] = 1,\n        ["ap"] = 0.5,\n    },\n    ["crownReplacementCosts"] =\n    {\n        [1] = 2,\n        [3] = 4,\n    },\n}\n'
  )
})

