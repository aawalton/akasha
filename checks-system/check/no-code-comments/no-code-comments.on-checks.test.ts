import { expect, test } from "bun:test"
import { resolve } from "node:path"
import noCodeComments from "./no-code-comments.check.code.attachment.ts"

const AKASHA = resolve(import.meta.dir, "../../..")

function verdict(path: string, text: string): readonly string[] {
  return noCodeComments.run({ root: AKASHA, path: `${AKASHA}/${path}`, body: Buffer.from(text) })
}

test("a source file carrying no comment passes", () => {
  expect(verdict("a/thing.ts", `export const x = 1\n`)).toEqual([])
})

test("a comment of prose fails", () => {
  expect(verdict("a/thing.ts", `// this explains the line below\nexport const x = 1\n`)).toHaveLength(1)
})

test("a comment reading as an instruction fails", () => {
  expect(verdict("a/thing.ts", `// never call this twice\nexport const x = 1\n`)).toHaveLength(1)
})

test("each form the list admits passes", () => {
  expect(verdict("a/thing.ts", `// @ts-expect-error\nexport const x = 1\n`)).toEqual([])
  expect(verdict("a/thing.ts", `// biome-ignore lint/style/noVar: it is needed\nexport const x = 1\n`)).toEqual([])
  expect(verdict("a/thing.ts", `/** @deprecated */\nexport const x = 1\n`)).toEqual([])
  expect(verdict("a/thing.ts", `/// <reference types="bun" />\nexport const x = 1\n`)).toEqual([])
})

test("a shebang passes on the first line and fails below it", () => {
  expect(verdict("a/run.sh", `#!/usr/bin/env bash\necho hi\n`)).toEqual([])
  expect(verdict("a/run.sh", `echo hi\n#!/usr/bin/env bash\n`)).toHaveLength(1)
})

test("a block comment carrying prose beside a directive fails", () => {
  expect(verdict("a/thing.ts", `/**\n * Why this exists.\n * @deprecated\n */\nexport const x = 1\n`)).toHaveLength(1)
})

test("a directive the list does not name fails", () => {
  expect(verdict("a/thing.ts", `// @ts-ignore\nexport const x = 1\n`)).toHaveLength(1)
  expect(verdict("a/thing.ts", `// eslint-disable-next-line\nexport const x = 1\n`)).toHaveLength(1)
})

test("a shellcheck directive passes where a plain hash comment fails", () => {
  expect(verdict("a/run.sh", `# shellcheck disable=SC2086\necho hi\n`)).toEqual([])
  expect(verdict("a/run.sh", `# what this does\necho hi\n`)).toHaveLength(1)
})

test("a file kind nothing here reads for comments is not judged", () => {
  expect(verdict("a/notes.md", `// this is not code\n`)).toEqual([])
})

test("a generated file is outside this check, by path or by header", () => {
  expect(verdict("a/generated/thing.ts", `// this explains the line below\n`)).toEqual([])
  expect(verdict("a/thing.generated.ts", `// this explains the line below\n`)).toEqual([])
  expect(verdict("a/thing.ts", `// @generated by something\n// this explains the line below\n`)).toEqual([])
})

test("a file under a fixtures directory is outside this check", () => {
  expect(verdict("a/__fixtures__/thing.ts", `// this explains the line below\n`)).toEqual([])
})

test("every comment outside the forms is named, not just the first", () => {
  expect(verdict("a/thing.ts", `// the first one\n// the second one\nexport const x = 1\n`)).toHaveLength(2)
})

test("text inside a string that looks like a comment is not one", () => {
  expect(verdict("a/thing.ts", `export const s = "// this explains the line below"\n`)).toEqual([])
})

test("a failure names the line the comment opens on", () => {
  expect(verdict("a/thing.ts", `export const x = 1\n\n// this explains the line above\n`)[0]).toContain("line 3")
})
