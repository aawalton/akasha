import { expect, test } from "bun:test"
import { resolve } from "node:path"
import importResolves from "./import-resolves.check.code.attachment.ts"

const AKASHA = resolve(import.meta.dir, "../../..")

const UNDER = "shared/design-system/src"

const ANSWERED = "@shared/design-badges/components/badge"

const UNANSWERED = "@shared/design-badges/components/badge.component.test"

const ALSO_UNANSWERED = "@shared/design-layout/components/page-tab-header.component.test"

function verdictIn(root: string, at: string, text: string): readonly string[] {
  return importResolves.run({ root, path: `${root}/${at}`, body: Buffer.from(text) })
}

function under(name: string, text: string): readonly string[] {
  return verdictIn(AKASHA, `${UNDER}/${name}`, text)
}

test("a specifier the package answers passes", () => {
  expect(under("thing.ts", `export { Badge } from "${ANSWERED}"`)).toEqual([])
})

test("a specifier naming a package here that the package does not answer fails", () => {
  expect(under("thing.ts", `export * from "${UNANSWERED}"`)).toHaveLength(1)
})

test("the failure names the specifier and the package it reached for", () => {
  const said = under("thing.ts", `export * from "${UNANSWERED}"`)[0] ?? ""
  expect(said).toContain(UNANSWERED)
  expect(said).toContain("@shared/design-badges")
})

test("a relative specifier is not judged", () => {
  expect(under("thing.ts", `import { x } from "./nowhere-at-all.ts"`)).toEqual([])
  expect(under("thing.ts", `import { x } from "../nowhere-at-all.ts"`)).toEqual([])
})

test("a specifier naming an absolute path is not judged", () => {
  expect(under("thing.ts", `const x = await import("/nowhere/at/all.ts")`)).toEqual([])
})

test("a package outside this repository is not judged, resolve or not", () => {
  expect(under("thing.ts", `import ts from "typescript"`)).toEqual([])
  expect(under("thing.tsx", `import { useState } from "react"`)).toEqual([])
  expect(under("thing.ts", `import { x } from "nothing-installed-under-this-name"`)).toEqual([])
})

test("a runtime builtin is not judged", () => {
  expect(under("thing.ts", `import { readFileSync } from "node:fs"`)).toEqual([])
})

test("a generated file is not judged, by its folder, its name or its header", () => {
  expect(under("generated/thing.ts", `export * from "${UNANSWERED}"`)).toEqual([])
  expect(under("thing.generated.ts", `export * from "${UNANSWERED}"`)).toEqual([])
  expect(under("thing.ts", `// @generated by something\nexport * from "${UNANSWERED}"`)).toEqual([])
})

test("a specifier standing inside a string literal does not fail", () => {
  expect(under("thing.ts", `const fixture = "import { x } from \\"${UNANSWERED}\\""`)).toEqual([])
})

test("a specifier standing inside a template literal does not fail", () => {
  const body = `const said = \`add the key to ${UNANSWERED}, or stop reading it\``
  expect(under("thing.ts", body)).toEqual([])
})

test("a type-only import is not judged", () => {
  expect(under("thing.ts", `import type { Badge } from "${UNANSWERED}"`)).toEqual([])
})

test("a dynamic import is judged as a static one is", () => {
  expect(under("thing.ts", `const held = await import("${UNANSWERED}")`)).toHaveLength(1)
})

test("a require call is judged as an import is", () => {
  expect(under("thing.ts", `const held = require("${UNANSWERED}")`)).toHaveLength(1)
})

test("a file opening with a shebang is judged like any other", () => {
  expect(under("thing.ts", `#!/usr/bin/env bun\nexport * from "${UNANSWERED}"`)).toHaveLength(1)
})

test("every specifier a file leaves unanswered is named, not just the first", () => {
  const body = `export * from "${UNANSWERED}"\nexport * from "${ALSO_UNANSWERED}"\n`
  expect(under("thing.ts", body)).toHaveLength(2)
})

test("one specifier written twice is named once", () => {
  const body = `import "${UNANSWERED}"\nexport * from "${UNANSWERED}"\n`
  expect(under("thing.ts", body)).toHaveLength(1)
})

test("a file that carries no code is not judged", () => {
  expect(under("notes.md", `export * from "${UNANSWERED}"`)).toEqual([])
  expect(under("thing.json", `export * from "${UNANSWERED}"`)).toEqual([])
})

test("a body that is not UTF-8 is not judged", () => {
  const path = `${AKASHA}/${UNDER}/thing.ts`
  expect(importResolves.run({ root: AKASHA, path, body: Buffer.from([0xff, 0xfe]) })).toEqual([])
})

test("a body whose syntax the scanner refuses is not judged", () => {
  expect(under("thing.ts", `export * from "${UNANSWERED}"\nfunction ( { ] }`)).toEqual([])
})

test("a root holding no packages judges nothing", () => {
  expect(verdictIn("/repo", `${UNDER}/thing.ts`, `export * from "${UNANSWERED}"`)).toEqual([])
})
