import { expect, test } from "bun:test"
import fileLength from "./file-length.check.code.attachment.ts"
import { CEILING_BYTES } from "./file-length.check.code.attachment.ts"

const ROOT = "/repo"

const OVER = "x".repeat(CEILING_BYTES + 1)

const UNDER = "x".repeat(CEILING_BYTES)

function verdict(path: string, body: string): readonly string[] {
  return fileLength.run({ root: ROOT, path: `${ROOT}/${path}`, body: Buffer.from(body) })
}

function bytesVerdict(path: string): readonly string[] {
  return fileLength.run({ root: ROOT, path: `${ROOT}/${path}`, body: Buffer.alloc(CEILING_BYTES + 1, 0xff) })
}

test("an authored file over the ceiling fails", () => {
  expect(verdict("page/thing.ts", OVER)).toHaveLength(1)
})

test("an authored file at the ceiling passes", () => {
  expect(verdict("page/thing.ts", UNDER)).toEqual([])
})

test("a lockfile over the ceiling passes", () => {
  expect(verdict("bun.lock", OVER)).toEqual([])
})

test("a lockfile in a nested package over the ceiling passes", () => {
  expect(verdict("native-shell/smilingjenny/bun.lock", OVER)).toEqual([])
})

test("an npm lockfile over the ceiling passes", () => {
  expect(verdict("native-shell/atlas/package-lock.json", OVER)).toEqual([])
})

test("a file merely named like a lockfile still fails", () => {
  expect(verdict("notes/bun.lock.txt", OVER)).toHaveLength(1)
  expect(verdict("notes/not-bun.lock", OVER)).toHaveLength(1)
  expect(verdict("notes/my-package-lock.json", OVER)).toHaveLength(1)
})

test("a file under a generated directory over the ceiling passes", () => {
  expect(verdict("page/generated/types.ts", OVER)).toEqual([])
})

test("a file carrying a generated header over the ceiling passes", () => {
  expect(verdict("page/thing.ts", `// @generated by something\n${OVER}`)).toEqual([])
})

test("a body that is not UTF-8 is judged on its length where its kind carries no bytes", () => {
  expect(bytesVerdict("page/blob.bin")).toHaveLength(1)
})

test("a file kind stating it carries bytes is not judged on its length", () => {
  expect(bytesVerdict("page/art.png")).toEqual([])
})

test("a texture is not judged, its kind being one that carries bytes", () => {
  expect(bytesVerdict("addon/metadata/Art/noty.dds")).toEqual([])
})

test("a kind carrying bytes passes on its length alone, not on being unreadable", () => {
  expect(verdict("page/art.png", OVER)).toEqual([])
})

test("a page of an unsplittable type over the ceiling passes", () => {
  expect(verdict("pages/story-chapter-royal-road/a/b/0001-first.story-chapter-royal-road.md", OVER)).toEqual([])
})

test("a chapter taken in from a book is unsplittable too", () => {
  expect(verdict("pages/book-chapter/plato/001-apology.book-chapter.md", OVER)).toEqual([])
})

test("a page of a type saying nothing is still judged, the ceiling being the default", () => {
  expect(verdict("pages/initiative/some-initiative.initiative.md", OVER)).toHaveLength(1)
})

test("a markdown file naming no page type is still judged", () => {
  expect(verdict("notes/README.md", OVER)).toHaveLength(1)
})

test("a working file under a dirty folder passes, nothing yet claiming it", () => {
  expect(verdict("stories/dirty/the-tower/PREP-LOG.md", OVER)).toEqual([])
})

test("a file merely named dirty is still judged", () => {
  expect(verdict("stories/dirty-notes/thing.md", OVER)).toHaveLength(1)
  expect(verdict("stories/dirty.md", OVER)).toHaveLength(1)
})

test("a file under a data folder passes, the folder saying its contents are data", () => {
  expect(verdict("temper/game-collections-addon/src/lorebooks/data/eidetic-book-data.ts", OVER)).toEqual([])
  expect(verdict("temper/game-collections-addon/src/skyshards/data/index.ts", OVER)).toEqual([])
})

test("a file merely named data is still judged", () => {
  expect(verdict("page/data.ts", OVER)).toHaveLength(1)
  expect(verdict("page/champions-data.ts", OVER)).toHaveLength(1)
})

test("a folder merely carrying data in its name is still judged", () => {
  expect(verdict("page/database/thing.ts", OVER)).toHaveLength(1)
  expect(verdict("page/metadata/thing.ts", OVER)).toHaveLength(1)
})
