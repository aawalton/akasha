import { expect, test } from "bun:test"
import { resolve } from "node:path"
import requireImportExtension from "./require-import-extension.check.code.attachment.ts"

const ROOT = "/repo"

const AKASHA = resolve(import.meta.dir, "../../..")

function verdict(path: string, text: string): readonly string[] {
  return requireImportExtension.run({ root: ROOT, path: `${ROOT}/${path}`, body: Buffer.from(text) })
}

function verdictHere(path: string, text: string): readonly string[] {
  return requireImportExtension.run({ root: AKASHA, path: `${AKASHA}/${path}`, body: Buffer.from(text) })
}

test("a relative import carrying its extension passes", () => {
  expect(verdict("a/thing.ts", `import { x } from "./thing.ts"`)).toEqual([])
})

test("a relative import written without its extension fails", () => {
  expect(verdict("a/thing.ts", `import { x } from "./thing"`)).toHaveLength(1)
})

test("a relative import reaching upward carrying its extension passes", () => {
  expect(verdict("a/thing.ts", `import { x } from "../a/b.tsx"`)).toEqual([])
})

test("a relative import reaching upward without its extension fails", () => {
  expect(verdict("a/thing.ts", `import { x } from "../a/b"`)).toHaveLength(1)
})

test("a specifier naming a workspace package is not judged", () => {
  expect(verdict("a/thing.ts", `import { x } from "@shared/design-primitives/components/button"`)).toEqual([])
})

test("a specifier naming a runtime builtin is not judged", () => {
  expect(verdict("a/thing.ts", `import { readFileSync } from "node:fs"`)).toEqual([])
})

test("a specifier naming a bare package is not judged", () => {
  expect(verdict("a/thing.ts", `import ts from "typescript"`)).toEqual([])
})

test("a relative import of json carrying its extension passes", () => {
  expect(verdict("a/thing.ts", `import held from "./data.json"`)).toEqual([])
})

test("a relative import of a stylesheet carrying its extension passes", () => {
  expect(verdict("a/thing.tsx", `import "./panel.css"`)).toEqual([])
})

test("a stem carrying a period of its own is still written without an extension", () => {
  expect(verdict("a/thing.ts", `import { x } from "./route.server"`)).toHaveLength(1)
})

test("a type-only import is judged as a value import is", () => {
  expect(verdict("a/thing.ts", `import type { X } from "./x.ts"`)).toEqual([])
  expect(verdict("a/thing.ts", `import type { X } from "./x"`)).toHaveLength(1)
})

test("every specifier a file writes bare is named, not just the first", () => {
  expect(verdict("a/thing.ts", `import "./one"\nimport "./two"\n`)).toHaveLength(2)
})

test("a file whose nearest project emits JavaScript is not judged", () => {
  expect(verdictHere("temper/addons/scripts/thing.ts", `import { x } from "./thing"`)).toEqual([])
})

// A PROJECT INHERITING `noEmit: false` EMITS JUST AS ONE WRITING IT DOES. Every addon project
// extends `temper/addons/tsconfig.base.json` without a word of its own about emit, and TypeScript
// refuses `allowImportingTsExtensions` against each of them with TS5096.
test("a project inheriting its emit from the config it extends is not judged either", () => {
  expect(verdictHere("temper/catalog-addon/src/thing.ts", `import { x } from "./constants"`)).toEqual([])
})

test("a file under a project that emits nothing is judged", () => {
  expect(verdictHere("checks-system/imports/thing.ts", `import { x } from "./imports"`)).toHaveLength(1)
})

test("a file that carries no code is not judged", () => {
  expect(verdict("a/notes.md", `import { x } from "./thing"`)).toEqual([])
})

test("a generated file is outside this check, whatever its path says", () => {
  expect(verdict("a/generated/thing.ts", `import { x } from "./thing"`)).toEqual([])
  expect(verdict("a/thing.generated.ts", `import { x } from "./thing"`)).toEqual([])
})

test("a generated file is outside this check, whatever its header says", () => {
  expect(verdict("a/thing.ts", `// @generated by something\nimport { x } from "./thing"`)).toEqual([])
})
