// Supabase emits `Database` as one file. Nothing in this repository regenerates it:
// there is no ops command, no package script, no CI job and no page that says how. The
// file arrived whole in the commit that moved the old code repository into akasha and
// has not been touched since; the only trace of what made it is a warning in
// `dotfiles/provision-workstation.sh` about a `gen-types` step needing a container
// runtime, and that step exists nowhere here. So it is updated by hand: paste a fresh
// Supabase dump in and split it again the same way.
//
// How to split it again: Supabase's output is one `export type Database = { public: {
// Tables: {...} Views: {...} Functions: {...} Enums: {...} CompositeTypes: {...} } }`,
// followed by the `Tables`/`TablesInsert`/`TablesUpdate`/`Enums`/`CompositeTypes`
// helper types and `Constants`. Whole it is far past the 15,000 bytes akasha will hold
// a file at. So the body of each of the three long sections is lifted out, dedented by
// four, and parked under ./database/ as a standalone type; `Functions` is longer than
// the ceiling on its own, so it is cut again at whole function entries and put back
// together by an interface that extends both halves. Everything else, the helpers and
// `Constants` included, stays here verbatim. Nothing imports the shards but this file,
// and this file still exports `Database` and `Json` exactly as it always did.

