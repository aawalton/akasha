export const summary = "Fold computed mastery C bottom-up over the whole Book of Everything tree, write each node's C back into its profile.md, and regenerate DASHBOARD.md"

import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import type { CommandHelp } from "../../ops/surface.ts"
import {
  type CoverageNode,
  computeCoverage,
  formatScore,
} from "../../lib/book-of-everything-coverage-fold.ts"
import {
  displayTitle,
  readNodeLabel,
  readNumberField,
  replaceComputedScore,
} from "../../lib/book-of-everything-profile.ts"
import { bookRoot } from "../../lib/book-of-everything-root.ts"
import { operationalError } from "../../lib/exit.ts"
import { parseArgs } from "../../lib/parse-args.ts"

export const help: CommandHelp = {
  irreversible: "irreversible",
  exits: [
    { code: 0, meaning: "the tree was folded, written back and DASHBOARD.md regenerated" },
    { code: 3, meaning: "operational error — the Book tree could not be read or written" },
  ],
  examples: ["ops ali fold"],
}

interface DiskNode {
  readonly dir: string
  readonly label: string
  readonly title: string
  readonly d: number
  readonly children: readonly DiskNode[]
}

interface ComputedPair {
  readonly disk: DiskNode
  readonly c: number
  readonly children: readonly ComputedPair[]
}

const CHILD_DIR = /^\d{2}-/

function readNode(dir: string): DiskNode {
  const content = readFileSync(join(dir, "profile.md"), "utf-8")
  const label = readNodeLabel(content)
  const childDirs = readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && CHILD_DIR.test(e.name))
    .map((e) => e.name)
    .sort()
  const children: DiskNode[] = []
  for (const name of childDirs) {
    const childDir = join(dir, name)
    try {
      readFileSync(join(childDir, "profile.md"), "utf-8")
    } catch {
      continue
    }
    children.push(readNode(childDir))
  }
  return { dir, label, title: displayTitle(label), d: readNumberField(content, "D"), children }
}

function toCoverageNode(n: DiskNode): CoverageNode {
  return { d: n.d, children: n.children.map(toCoverageNode) }
}

function zip(disk: DiskNode, folded: ReturnType<typeof computeCoverage>): ComputedPair {
  const children = disk.children.map((child, i) => {
    const f = folded.children[i]
    if (f === undefined) throw new Error("disk/folded tree shape mismatch")
    return zip(child, f)
  })
  return { disk, c: folded.c, children }
}

function writeBack(disk: DiskNode, computedC: number, children: readonly ComputedPair[]): undefined {
  const path = join(disk.dir, "profile.md")
  writeFileSync(path, replaceComputedScore(readFileSync(path, "utf-8"), computedC))
  for (const { disk: d, c, children: cc } of children) writeBack(d, c, cc)
}

export default async function aliFold(args: readonly string[]): Promise<void> {
  parseArgs(help, args)

  const BOOK_ROOT = bookRoot("book-of-everything")

  let zipped: ComputedPair
  try {
    const root = readNode(BOOK_ROOT)
    zipped = zip(root, computeCoverage(toCoverageNode(root)))
    writeBack(zipped.disk, zipped.c, zipped.children)
  } catch (e) {
    throw operationalError(e instanceof Error ? e.message : String(e))
  }

  const lines: string[] = []
  lines.push("# Book of Everything — Coverage Dashboard")
  lines.push("")
  lines.push("<!-- Generated by `ops ali fold`. Do not edit by hand. -->")
  lines.push("")
  lines.push(`**Root coverage (C): ${formatScore(zipped.c)} / 7**`)
  lines.push("")
  lines.push("How much of reality Alan's one conceptual model explains, and how well —")
  lines.push("the whole tree folded by C(parent) = ½·D + ½·mean(children C). All scores")
  lines.push("0–7 to two decimals.")
  lines.push("")
  lines.push("## By Part")
  lines.push("")
  lines.push("| # | Part | C |")
  lines.push("| --- | --- | --- |")
  let partNo = 0
  for (const part of zipped.children) {
    partNo++
    lines.push(`| ${partNo} | ${part.disk.title} | ${formatScore(part.c)} |`)
  }
  lines.push("")
  lines.push("## By Division")
  lines.push("")
  lines.push("| Part | Division | C |")
  lines.push("| --- | --- | --- |")
  for (const part of zipped.children) {
    for (const division of part.children) {
      lines.push(`| ${part.disk.title} | ${division.disk.title} | ${formatScore(division.c)} |`)
    }
  }
  lines.push("")

  try {
    writeFileSync(join(BOOK_ROOT, "DASHBOARD.md"), `${lines.join("\n")}`)
  } catch (e) {
    throw operationalError(e instanceof Error ? e.message : String(e))
  }

  const divCount = zipped.children.reduce((a, p) => a + p.children.length, 0)
  process.stdout.write(`fold: root C = ${formatScore(zipped.c)}\n`)
  process.stdout.write(
    `fold: folded ${zipped.children.length} parts + ${divCount} divisions; DASHBOARD.md regenerated\n`
  )
}
