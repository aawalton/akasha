
import { afterEach, beforeEach, describe, expect, test } from "bun:test"
import { mkdtempSync, rmSync } from "node:fs"
import { tmpdir } from "node:os"
import { type Emission, readOne } from "../../agent/read-one.ts"
import { type Fixture, fixture } from "./fixture.ts"

let at: Fixture

beforeEach(() => {
  at = fixture()
})

afterEach(() => {
  at.dispose()
})

const OVERSIZE = `${Array.from({ length: 4000 }, (_, i) => `export const name${i}: string`).join("\n")}\n`

function firstSight(relPath: string): Emission {
  const workspace = mkdtempSync(`${tmpdir()}/read-one-`)
  try {
    return readOne({
      named: relPath,
      absolute: `${at.root}/${relPath}`,
      reading: null,
      forced: false,
      root: at.root,
      workspace,
    })
  } finally {
    rmSync(workspace, { recursive: true, force: true })
  }
}

describe("what a read of a generated file returns instead of its body", () => {
  test("the body under test is far past what one answer holds, so no case here is vacuous", () => {
    expect(OVERSIZE.length).toBeGreaterThan(28_000)
  })

  test("a file under a generated directory returns what it is, and records it read whole", () => {
    const relPath = "packages/thing/src/generated/enums.d.ts"
    at.put(relPath, OVERSIZE)
    const emission = firstSight(relPath)
    expect(emission.body).toBeNull()
    expect(emission.headline).toContain(`${OVERSIZE.length} bytes`)
    expect(emission.record).not.toBeNull()
  })

  test("a file whose name carries the generated marker returns what it is", () => {
    const relPath = "packages/thing/src/schema.generated.ts"
    at.put(relPath, OVERSIZE)
    const emission = firstSight(relPath)
    expect(emission.body).toBeNull()
    expect(emission.record).not.toBeNull()
  })

  test("a file whose header says it is generated returns what it is", () => {
    const relPath = "packages/thing/src/schema.ts"
    at.put(relPath, `// @generated by gen-schema\n${OVERSIZE}`)
    const emission = firstSight(relPath)
    expect(emission.body).toBeNull()
    expect(emission.record).not.toBeNull()
  })

  test("the same body at an authored path still comes back whole", () => {
    const relPath = "packages/thing/src/schema.ts"
    at.put(relPath, OVERSIZE)
    const emission = firstSight(relPath)
    expect(emission.headline).toContain("the whole file follows")
    expect(emission.body).toContain("export const name0: string")
  })

  test("a path merely containing the word generated elsewhere still comes back whole", () => {
    const relPath = "tools/thing/regenerated-rows.ts"
    at.put(relPath, OVERSIZE)
    expect(firstSight(relPath).body).not.toBeNull()
  })
})
