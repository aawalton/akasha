import { describe, expect, test } from "bun:test"
import { mkdtempSync, rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import {
  readEnvLocal,
  resolveEnvLocalPath,
  synthesizeNextPublicCopies,
} from "../lib/dev-server-bootstrap.ts"

const SCRATCH = "/var/tmp"

const FIXTURE_WORKTREE = "/var/tmp/worktree-fixture"

describe("synthesizeNextPublicCopies", () => {
  test("synthesizes NEXT_PUBLIC_SUPABASE_URL from SUPABASE_URL", () => {
    const kv = new Map([["SUPABASE_URL", "https://supabase.alanwalton.com"]])
    synthesizeNextPublicCopies(kv)
    expect(kv.get("NEXT_PUBLIC_SUPABASE_URL")).toBe("https://supabase.alanwalton.com")
    expect(kv.get("SUPABASE_URL")).toBe("https://supabase.alanwalton.com")
  })

  test("synthesizes NEXT_PUBLIC_SUPABASE_ANON_KEY from SUPABASE_ANON_KEY", () => {
    const kv = new Map([["SUPABASE_ANON_KEY", "anon-jwt"]])
    synthesizeNextPublicCopies(kv)
    expect(kv.get("NEXT_PUBLIC_SUPABASE_ANON_KEY")).toBe("anon-jwt")
  })

  test("synthesizes both pairs when both non-prefixed sources are present", () => {
    const kv = new Map([
      ["SUPABASE_URL", "https://supabase.alanwalton.com"],
      ["SUPABASE_ANON_KEY", "anon-jwt"],
    ])
    synthesizeNextPublicCopies(kv)
    expect(kv.get("NEXT_PUBLIC_SUPABASE_URL")).toBe("https://supabase.alanwalton.com")
    expect(kv.get("NEXT_PUBLIC_SUPABASE_ANON_KEY")).toBe("anon-jwt")
  })

  test("an existing NEXT_PUBLIC_ value wins, even where the source differs", () => {
    const kv = new Map([
      ["SUPABASE_URL", "http://auth-proxy.svc.cluster.local:3080"],
      ["NEXT_PUBLIC_SUPABASE_URL", "https://supabase.alanwalton.com"],
    ])
    synthesizeNextPublicCopies(kv)
    expect(kv.get("NEXT_PUBLIC_SUPABASE_URL")).toBe("https://supabase.alanwalton.com")
    expect(kv.get("SUPABASE_URL")).toBe("http://auth-proxy.svc.cluster.local:3080")
  })

  test("no-op when no source keys are present", () => {
    const kv = new Map([
      ["NEXT_PUBLIC_SUPABASE_ANON_KEY", "anon-jwt"],
      ["SUPABASE_SERVICE_ROLE_KEY", "service-role"],
    ])
    const sizeBefore = kv.size
    synthesizeNextPublicCopies(kv)
    expect(kv.size).toBe(sizeBefore)
    expect(kv.has("NEXT_PUBLIC_SUPABASE_URL")).toBe(false)
  })

  test("does not synthesize unrelated SUPABASE_* keys", () => {
    const kv = new Map([["SUPABASE_SERVICE_ROLE_KEY", "service-role"]])
    synthesizeNextPublicCopies(kv)
    expect(kv.has("NEXT_PUBLIC_SUPABASE_SERVICE_ROLE_KEY")).toBe(false)
  })

  test("sets NEXT_PUBLIC_ELECTRIC_URL to the shared literal when absent", () => {
    const kv = new Map([["SUPABASE_URL", "https://supabase.alanwalton.com"]])
    synthesizeNextPublicCopies(kv)
    expect(kv.get("NEXT_PUBLIC_ELECTRIC_URL")).toBe(
      "https://supabase.alanwalton.com/electric/v1/shape"
    )
  })

  test("an explicit NEXT_PUBLIC_ELECTRIC_URL from the sops map wins", () => {
    const kv = new Map([
      ["NEXT_PUBLIC_ELECTRIC_URL", "https://electric-override.example.com/v1/shape"],
    ])
    synthesizeNextPublicCopies(kv)
    expect(kv.get("NEXT_PUBLIC_ELECTRIC_URL")).toBe(
      "https://electric-override.example.com/v1/shape"
    )
  })
})

describe("readEnvLocal", () => {
  function withTempFile(contents: string, fn: (path: string) => undefined): undefined {
    const dir = mkdtempSync(join(SCRATCH, "envlocal-"))
    const path = join(dir, ".env.local")
    writeFileSync(path, contents, { mode: 0o600 })
    try {
      fn(path)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  }

  test("parses bare KEY=value pairs", () => {
    withTempFile("NEXT_PUBLIC_SUPABASE_URL=https://supabase.alanwalton.com\n", (path) => {
      expect(readEnvLocal(path).NEXT_PUBLIC_SUPABASE_URL).toBe("https://supabase.alanwalton.com")
    })
  })

  test("strips outer double quotes from quoted values", () => {
    withTempFile('JWT="eyJhbGciOiJIUzI1NiJ9.payload.sig"\n', (path) => {
      expect(readEnvLocal(path).JWT).toBe("eyJhbGciOiJIUzI1NiJ9.payload.sig")
    })
  })

  test("preserves whitespace inside quoted values", () => {
    withTempFile('LABEL="a value with spaces"\n', (path) => {
      expect(readEnvLocal(path).LABEL).toBe("a value with spaces")
    })
  })

  test("treats KEY= with no value as the empty string, the cookie-domain shape", () => {
    withTempFile("NEXT_PUBLIC_SUPABASE_COOKIE_DOMAIN=\n", (path) => {
      expect(readEnvLocal(path).NEXT_PUBLIC_SUPABASE_COOKIE_DOMAIN).toBe("")
    })
  })

  test("treats a quoted empty value as the empty string", () => {
    withTempFile('EMPTY=""\n', (path) => {
      expect(readEnvLocal(path).EMPTY).toBe("")
    })
  })

  test("skips comment and blank lines", () => {
    withTempFile("# generated by bootstrap\n\nKEY=value\n", (path) => {
      const env = readEnvLocal(path)
      expect(env.KEY).toBe("value")
      expect(Object.keys(env)).toEqual(["KEY"])
    })
  })

  test("returns the whole shape a dev-server start needs from bootstrap output", () => {
    const file = [
      "# Generated by `ops dev-server bootstrap` — do not commit.",
      "# app=alanwalton secrets=/x/alanwalton/web/deploy/secrets.sops.yaml",
      "NEXT_PUBLIC_SUPABASE_URL=https://supabase.alanwalton.com",
      "NEXT_PUBLIC_SUPABASE_ANON_KEY=eyJhbGc.anon.sig",
      'SUPABASE_SERVICE_ROLE_KEY="eyJhbGc.service.sig"',
      "NEXT_PUBLIC_SUPABASE_COOKIE_DOMAIN=",
      "",
    ].join("\n")
    withTempFile(file, (path) => {
      const env = readEnvLocal(path)
      expect(env.NEXT_PUBLIC_SUPABASE_URL).toBe("https://supabase.alanwalton.com")
      expect(env.NEXT_PUBLIC_SUPABASE_ANON_KEY).toBe("eyJhbGc.anon.sig")
      expect(env.SUPABASE_SERVICE_ROLE_KEY).toBe("eyJhbGc.service.sig")
      expect(env.NEXT_PUBLIC_SUPABASE_COOKIE_DOMAIN).toBe("")
    })
  })

  test("throws where the file does not exist, the caller having to check first", () => {
    expect(() => readEnvLocal(`${SCRATCH}/does-not-exist-envlocal.zzz`)).toThrow()
  })
})

describe("resolveEnvLocalPath", () => {
  test("resolves alanwalton under the worktree it is given", async () => {
    expect(await resolveEnvLocalPath(FIXTURE_WORKTREE, "alanwalton")).toBe(
      `${FIXTURE_WORKTREE}/alanwalton/web/.env.local`
    )
  })

  test("rejects an unknown app", async () => {
    await expect(resolveEnvLocalPath(FIXTURE_WORKTREE, "nope")).rejects.toThrow(/unknown app: nope/)
  })
})
